import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import sharp from 'sharp';

const read = name => fs.readFile(name, 'utf8');
const pkg = JSON.parse(await read('package.json'));
if (!/^\d+\.\d+\.\d+$/.test(pkg.version)) throw Error('Use a three-part semantic version.');
const source = await read('src/core.user.js');
const userscript = source.replaceAll('__VERSION__', pkg.version);
if (userscript.includes('__VERSION__')) throw Error('Unresolved version.');
await fs.writeFile('Zynubo.user.js', userscript);
const body = userscript.replace(/^\/\/ ==UserScript==[\s\S]*?\/\/ ==\/UserScript==\s*/, '');
const shim = (await read('src/extension/shim.js')).replace(/    function readBridgeDetail\(event\) \{[\s\S]*?\n    \}\n/, '');
const anchor = "    const SCRIPT_NAME = 'Zynubo';";
if (!body.includes(anchor) || !body.trimEnd().endsWith('})();')) throw Error('Core build anchors changed.');
const main = '// Generated by build/build.mjs. See LICENSE and THIRD_PARTY_NOTICES.md.\n' +
    body.replace(anchor, shim + '\n' + anchor).replace(/\}\)\(\);\s*$/, (await read('src/extension/commands.js')) + '\n})();\n');
const base = JSON.parse(await read('src/extension/manifest.json'));
const rules = JSON.parse(await read('src/extension/network-rules.json'));
for (const pattern of rules.interceptPatterns) {
    if (!body.includes(`'${pattern}'`)) throw Error(`Missing core intercept pattern: ${pattern}`);
}
await fs.mkdir('dist', { recursive: true });
for (const browser of ['chromium', 'firefox']) {
    const dir = `dist/${browser}`;
    await fs.rm(dir, { recursive: true, force: true });
    await fs.mkdir(`${dir}/icons`, { recursive: true });
    await fs.mkdir(`${dir}/rules`, { recursive: true });
    const manifest = structuredClone(base);
    manifest.version = pkg.version;
    if (browser === 'firefox') {
        delete manifest.minimum_chrome_version;
        manifest.background = { scripts: ['background.js'] };
        manifest.browser_specific_settings = {
            gecko: { id: 'zynubo@rafelolv.github.io', strict_min_version: '140.0',
                data_collection_permissions: { required: ['none'] } },
            gecko_android: { strict_min_version: '142.0' }
        };
    }
    await fs.writeFile(`${dir}/manifest.json`, JSON.stringify(manifest, null, 2) + '\n');
    await fs.writeFile(`${dir}/main.js`, main);
    await fs.writeFile(`${dir}/rules/network-blocks.json`, JSON.stringify(rules.dnrRules) + '\n');
    for (const file of ['background.js', 'bridge.js', 'popup.html', 'popup.css', 'popup.js']) {
        let content = await read(`src/extension/${file}`);
        if (browser === 'firefox' && file === 'background.js') {
            // Firefox has no matched-rule feedback API. Keep its unavailable
            // diagnostic explicit, without shipping unsupported API references.
            const start = content.indexOf('async function getDnrDiagnostics(tabId) {');
            const end = content.indexOf('// Returns a Promise that resolves', start);
            if (start < 0 || end < 0) throw Error('DNR adapter anchors changed');
            content = content.slice(0, start) +
                "async function getDnrDiagnostics() { return unavailableDnrDiagnostics('api-unavailable'); }\n\n" + content.slice(end);
        }
        await fs.writeFile(`${dir}/${file}`, content);
    }
    for (const file of ['LICENSE', 'THIRD_PARTY_NOTICES.md']) await fs.copyFile(file, `${dir}/${file}`);
    for (const size of [16, 32, 48, 128]) {
        await sharp('images/icon.svg').resize(size, size).png().toFile(`${dir}/icons/icon${size}.png`);
    }
    await fs.writeFile(`${dir}/build-info.json`, JSON.stringify({ version: pkg.version,
        coreSha256: crypto.createHash('sha256').update(userscript).digest('hex'),
        mainSha256: crypto.createHash('sha256').update(main).digest('hex') }, null, 2) + '\n');
}
await sharp('images/icon.svg').resize(128, 128).png().toFile('icon.png');
console.log(`Built Zynubo ${pkg.version}: userscript, Chromium, Firefox.`);
